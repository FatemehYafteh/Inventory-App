/** Shorthand for schemas: `m.NAME_REQUIRED` is the English text of that message code. */
export const m = MESSAGES;

const CODE_BY_MESSAGE = new Map(Object.entries(MESSAGES).map(([code, text]) => [text, code]));

/** The message code for an exact English text, or null when it is not in the catalogue. */
export function codeForMessage(text) {
  return CODE_BY_MESSAGE.get(text) ?? null;
}

/** The English text for a message code or an `AppError` code, or null when unknown. */
export function messageFor(code) {
  return MESSAGES[code] ?? CODES[code] ?? null;
}
